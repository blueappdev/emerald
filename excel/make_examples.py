worksheet.write(0,2,'Bold format', bold_format)
worksheet.write(0,3,'Bold italic format', bold_italic_format)
worksheet.write(0,4,'Fancy format', fancy_format)
worksheet.write(0,5,'White format', white_format)
workbook.close()

