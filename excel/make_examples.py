# example10
workbook = xlsxwriter.Workbook('examples/example10.xlsx')
workbook.set_properties({'created': datetime.datetime(2020,1,1,12,0,0)})
red_format = workbook.add_format({'bg_color': '#FF0000'})
green_format = workbook.add_format({'bg_color': 'green'})
bold_format = workbook.add_format({'bold': True})
bold_italic_format = workbook.add_format({'bold': True, 'italic': True})
fancy_format = workbook.add_format({'bg_color': 'green', 'bold': True, 'italic': True})
white_format = workbook.add_format({'bg_color': 'green', 'bold': True, 'italic': True, 'fg_color':'white'})
date_format = workbook.add_format({'num_format': 'mmmm d yyyy'})

worksheet = workbook.add_worksheet(name='Data Types')
worksheet.write(0,0,'String')
worksheet.write(0,1,'Example')
worksheet.write(1,0,'Integer')
worksheet.write(1,1,123)
worksheet.write(1,2,-123)
worksheet.write(2,0,'Float')
worksheet.write(2,1,123.456)
worksheet.write(2,2,-123.456)
worksheet.write(3,0,'Boolean')
worksheet.write(3,1,True)
worksheet.write(3,2,False)
worksheet.write(4,0,'None')
worksheet.write(4,1,None)
worksheet.write(5,0,'FixedPoint')
worksheet.write(5,1,decimal.Decimal(2)/3)
worksheet.write(5,2,-decimal.Decimal(2)/3)
worksheet.write(6,0,'Date')
worksheet.write(6,1,datetime.datetime.strptime('2013-01-13', "%Y-%m-%d"))
worksheet.write_datetime(6,1,datetime.datetime.strptime('2013-01-13', "%Y-%m-%d"))
worksheet.write(6,2,datetime.datetime.strptime('2013-01-13', "%Y-%m-%d"), date_format)
worksheet.write(7,2,datetime.datetime.strptime('2000-01-01', "%Y-%m-%d"), date_format)
worksheet.write(8,2,datetime.datetime.strptime('1990-01-01', "%Y-%m-%d"), date_format)
worksheet.write(9,2,datetime.datetime.strptime('1980-01-01', "%Y-%m-%d"), date_format)
worksheet.write(10,2,datetime.datetime.strptime('1970-01-01', "%Y-%m-%d"), date_format)
worksheet = workbook.add_worksheet(name='MySheet')
worksheet.set_row(2, 24)
worksheet.write(0,0,'Hallo', green_format)
worksheet.write(0,1,'World')
worksheet.write(0,2,'Hello')
