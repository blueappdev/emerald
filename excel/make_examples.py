# example12 label and merged cells in one line
workbook = xlsxwriter.Workbook('examples/example12.xlsx')
workbook.set_properties({'created': datetime.datetime(2020,1,1,12,0,0)})
worksheet = workbook.add_worksheet()
worksheet.set_column(0,0,15)
worksheet.set_row(0,30)
label_format = workbook.add_format({'bg_color':'#C0A080', 'bold':False, 'font_size':20, 'valign':'vcenter', 'align':'center'})
worksheet.write(0,0,'LABEL', label_format)

merge_format = workbook.add_format({'italic':True, 'bold':False, 'font_size':20, 'valign':'vcenter'})
worksheet.merge_range('B1:H1', 'My New report', merge_format)

worksheet.write(2,0,'My')
worksheet.write(3,0,'Data')
worksheet.write(4,0,'comes')
worksheet.write(5,0,'here.')
workbook.close()

